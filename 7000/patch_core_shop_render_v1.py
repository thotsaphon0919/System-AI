    draw.rounded_rectangle((595, 1040, 785, 1138), radius=26, fill=(255, 154, 42, 235))
    draw.text((635, 1060), "SALE", fill=(20, 10, 5, 255), font=font_mid)

    draw.text((92, 1225), "Generated by INFINI Core Ability", fill=(255, 183, 88, 220), font=font_small)

    name = "core_render_" + _CoreUuid.uuid4().hex + ".png"
    out = _CORE_UPLOADS / name
    canvas.convert("RGB").save(out, "PNG")

    return {
        "name": name,
        "url": "/ai-core-file/" + name,
        "kind": "rendered_shop_sheet"
    }

